export type DriverLang = "ar" | "en" | "ur";
export const DRIVER_LANGS: { value: DriverLang; label: string }[] = [
  { value: "ar", label: "عربي" },
  { value: "en", label: "English" },
  { value: "ur", label: "اردو" },
];

const STORAGE_KEY = "althumama.driverLang";
const isLang = (value: unknown): value is DriverLang => value === "ar" || value === "en" || value === "ur";

/** اللغة التي اختارها السائق على هذا الهاتف (أو null إن لم يختر). */
export function storedDriverLang(): DriverLang | null {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    return isLang(stored) ? stored : null;
  } catch {
    return null;
  }
}

/** أول مرة: لغة الهاتف إن كانت إحدى اللغات الثلاث، وإلا العربية. */
function phoneLang(): DriverLang {
  for (const tag of navigator.languages ?? [navigator.language]) {
    const code = tag.slice(0, 2).toLowerCase();
    if (isLang(code)) return code;
  }
  return "ar";
}

export function useDriverLang(): [DriverLang, (lang: DriverLang) => void] {
  const [lang, setLang] = useState<DriverLang>(() => storedDriverLang() ?? phoneLang());
  return [lang, (next) => {
    setLang(next);
    try {
      localStorage.setItem(STORAGE_KEY, next);
    } catch {
      /* التخزين غير متاح: تبقى اللغة لهذه الزيارة */
    }
  }];
}

