/** عدد المواعيد بالعربية: موعد واحد، موعدان، 3 مواعيد، 11 موعدًا */
const countText = (count: number) => (count === 1 ? "موعد واحد" : count === 2 ? "موعدين" : count <= 10 ? `${count} مواعيد` : `${count} موعدًا`);

/** لغة الواجهة (تُحفظ على هذا الجهاز فقط). */
export function useLang(): [Lang, (lang: Lang) => void] {
  const [lang, setLang] = useState<Lang>(() => {
    try {
      return localStorage.getItem(STORAGE_KEY) === "en" ? "en" : "ar";
    } catch {
      return "ar";
    }
  });
  return [lang, (next) => {
    setLang(next);
    try {
      localStorage.setItem(STORAGE_KEY, next);
    } catch {
      /* التخزين غير متاح */
    }
  }];
}

